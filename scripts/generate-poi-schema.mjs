#!/usr/bin/env node

/**
 * Generate the planetiler schema YAML for the custom outdoor POIs.
 *
 * Reads pois/catalogue.yml (the single source of truth) and writes
 * pois/pois-schema.yml for the planetiler profile that builds the
 * self-hosted outdoor_pois tiles (tile.ogis.app /pois).
 *
 * Only `source: custom` entries become features — one feature per entry,
 * in catalogue order. The OSM extract area defaults to `geofabrik:italy`
 * and can be overridden with `--area=geofabrik:world` or `POI_AREA=...`.
 *
 * Usage:
 *   node scripts/generate-poi-schema.mjs            # geofabrik:italy
 *   node scripts/generate-poi-schema.mjs --area=geofabrik:world
 *   POI_AREA=geofabrik:world node scripts/generate-poi-schema.mjs
 */

import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import YAML from "yaml";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const CATALOGUE_FILE = resolve(ROOT, "pois", "catalogue.yml");
const OUTPUT_FILE = resolve(ROOT, "pois", "pois-schema.yml");

// Kinds that also carry an elevation attribute.
const ELE_KINDS = new Set(["hut", "shelter", "viewpoint", "pass"]);

function parseAreaArg(argv) {
  for (const arg of argv) {
    if (arg.startsWith("--area=")) return arg.slice("--area=".length);
  }
  return null;
}

const area =
  parseAreaArg(process.argv.slice(2)) ??
  process.env.POI_AREA ??
  "geofabrik:italy";

const catalogue = YAML.parse(readFileSync(CATALOGUE_FILE, "utf8"));
const customEntries = catalogue.pois.filter((e) => e.source === "custom");

const schema = {
  schema_name: "Outdoor POIs",
  schema_description:
    "Outdoor points of interest (huts, shelters, water, parking, viewpoints, passes) for the outdoors style",
  attribution:
    '<a href="https://www.openstreetmap.org/copyright" target="_blank">&copy; OpenStreetMap contributors</a>',
  version: "1.0.0",
  is_overlay: true,
  sources: {
    osm: {
      type: "osm",
      url: area,
    },
  },
  layers: [
    {
      id: "outdoor_pois",
      features: customEntries.map((entry) => {
        const attributes = [
          { key: "kind", value: entry.kind },
          { key: "name", tag_value: "name" },
        ];
        if (ELE_KINDS.has(entry.kind)) {
          attributes.push({ key: "ele", tag_value: "ele" });
        }
        return {
          source: "osm",
          geometry: "point",
          min_zoom: entry.min_zoom,
          include_when: entry.include_when,
          attributes,
        };
      }),
    },
  ],
};

const header = [
  "# GENERATED FILE — do not edit by hand.",
  "# Generated by scripts/generate-poi-schema.mjs from pois/catalogue.yml.",
  "# Change the catalogue instead, then run: npm run pois:schema",
  "",
  "",
].join("\n");

writeFileSync(
  OUTPUT_FILE,
  header + YAML.stringify(schema, { lineWidth: 0 }),
  "utf8",
);

console.log(
  `[pois:schema] wrote ${customEntries.length} features to ${OUTPUT_FILE} ` +
    `(area: ${area})`,
);
