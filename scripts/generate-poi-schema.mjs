#!/usr/bin/env node

/**
 * Generate the planetiler schema YAML for the custom outdoor POIs.
 *
 * Reads OUTDOOR_POI from scripts/poi-config.mjs (the shared config) and
 * writes pois/pois-schema.yml for the planetiler profile that builds the
 * self-hosted outdoor_pois tiles (tile.ogis.app /pois).
 *
 * One feature per kind in OUTDOOR_POI.kinds order, all at min_zoom 12 with
 * point (centroid) geometry and attributes kind + name, plus ele for the
 * showEle kinds. Each kind's include_when OSM-tag selector comes from the
 * INCLUDE_WHEN map below.
 *
 * The OSM extract area defaults to `geofabrik:italy` and can be overridden
 * with `--area=geofabrik:world` or `POI_AREA=...`.
 *
 * Usage:
 *   node scripts/generate-poi-schema.mjs            # geofabrik:italy
 *   node scripts/generate-poi-schema.mjs --area=geofabrik:world
 *   POI_AREA=geofabrik:world node scripts/generate-poi-schema.mjs
 */

import { writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import YAML from "yaml";
import { OUTDOOR_POI } from "./poi-config.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const OUTPUT_FILE = resolve(ROOT, "pois", "pois-schema.yml");

// include_when OSM-tag selector per kind. Keep in sync with
// OUTDOOR_POI.kinds.
const INCLUDE_WHEN = {
  hut: { tourism: ["alpine_hut", "wilderness_hut"] },
  shelter: { amenity: "shelter" },
  viewpoint: { tourism: "viewpoint" },
  campsite: { tourism: ["camp_site", "camp_pitch"] },
  picnic_site: { tourism: "picnic_site" },
  drinking_water: { amenity: "drinking_water" },
  trailhead: { highway: "trailhead" },
  pass: { natural: "saddle" },
  ranger_station: { amenity: "ranger_station" },
  castle: { historic: "castle" },
  information: { tourism: "information" },
  parking: { amenity: "parking" },
  park: { leisure: "park" },
  toilets: { amenity: "toilets" },
  playground: { leisure: "playground" },
  ferry: { amenity: "ferry_terminal" },
  lighthouse: { man_made: "lighthouse" },
  skiing: { leisure: "ski_resort" },
};

function parseAreaArg(argv) {
  for (const arg of argv) {
    if (arg.startsWith("--area=")) return arg.slice("--area=".length);
  }
  return null;
}

const area =
  parseAreaArg(process.argv.slice(2)) ??
  process.env.POI_AREA ??
  "geofabrik:italy";

const schema = {
  schema_name: "Outdoor POIs",
  schema_description:
    "Outdoor points of interest (huts, shelters, viewpoints, campsites, picnic sites, drinking water, trailheads, passes, ranger stations) for the outdoors style",
  attribution:
    '<a href="https://www.openstreetmap.org/copyright" target="_blank">&copy; OpenStreetMap contributors</a>',
  version: "1.0.0",
  is_overlay: true,
  sources: {
    osm: {
      type: "osm",
      url: area,
    },
  },
  layers: [
    {
      id: "outdoor_pois",
      features: OUTDOOR_POI.kinds.map((kind) => {
        const attributes = [
          { key: "kind", value: kind.kind },
          { key: "name", tag_value: "name" },
        ];
        if (kind.showEle) {
          attributes.push({ key: "ele", tag_value: "ele" });
        }
        return {
          source: "osm",
          geometry: "centroid",
          min_zoom: 12,
          include_when: INCLUDE_WHEN[kind.kind],
          attributes,
        };
      }),
    },
  ],
};

const header = [
  "# GENERATED FILE — do not edit by hand.",
  "# Generated by scripts/generate-poi-schema.mjs from scripts/poi-config.mjs.",
  "# Change the config instead, then run: npm run pois:schema",
  "",
  "",
].join("\n");

writeFileSync(
  OUTPUT_FILE,
  header + YAML.stringify(schema, { lineWidth: 0 }),
  "utf8",
);

console.log(
  `[pois:schema] wrote ${OUTDOOR_POI.kinds.length} features to ${OUTPUT_FILE} ` +
    `(area: ${area})`,
);
